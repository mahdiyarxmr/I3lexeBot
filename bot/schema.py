"""PostgreSQL schema for the i3l.exe bot.

This module is the single source of truth for the database layout. It is used
by both the runtime (``bot.db.Database.ensure_schema``) and the one-off SQLite
import utility (``scripts/migrate_sqlite_to_postgres.py``) so the two can never
drift apart.

The schema intentionally mirrors the legacy SQLite database (``i3l.db`` and its
backups) *exactly*: every table, column and unique constraint that the old
bot used is preserved, including the historical ``owner_votes``, ``profile_votes``,
``roles`` and ``profile_photos`` tables that newer versions of the bot no longer
write to. New tables (``conversation_state``, ``rate_limits``) back the
serverless-safe conversation state and anti-spam limiter.

Identity columns are declared ``GENERATED BY DEFAULT AS IDENTITY`` so that the
import utility can copy explicit primary-key values from SQLite and then reset
the sequence with ``setval``.
"""

# --------------------------------------------------------------------------
# Tables + unique constraints + indexes
# --------------------------------------------------------------------------
SCHEMA_SQL = """
CREATE TABLE IF NOT EXISTS media (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_id       TEXT NOT NULL,
    kind          TEXT NOT NULL,
    sender_id     BIGINT NOT NULL,
    username      TEXT,
    approved      INTEGER DEFAULT 0,
    created_at    TEXT,
    review_status TEXT DEFAULT 'legacy_pending',
    reviewed_by   BIGINT,
    reviewed_name TEXT,
    reviewed_at   TEXT
);

CREATE TABLE IF NOT EXISTS votes (
    media_id BIGINT,
    voter_id BIGINT,
    vote     INTEGER,
    CONSTRAINT votes_uniq_media_voter UNIQUE (media_id, voter_id)
);

-- Legacy table (older versions). Preserved for historical data.
CREATE TABLE IF NOT EXISTS owner_votes (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    media_id BIGINT NOT NULL,
    voter_id BIGINT NOT NULL,
    vote     INTEGER NOT NULL
);

-- Legacy table (older versions). Preserved for historical data.
CREATE TABLE IF NOT EXISTS profile_votes (
    profile_id BIGINT,
    voter_id   BIGINT,
    vote       INTEGER,
    CONSTRAINT profile_votes_uniq_profile_voter UNIQUE (profile_id, voter_id)
);

CREATE TABLE IF NOT EXISTS users (
    user_id          BIGINT PRIMARY KEY,
    username         TEXT,
    first_name       TEXT,
    bio              TEXT DEFAULT '',
    color            TEXT DEFAULT 'blue',
    role             TEXT DEFAULT 'Member',
    profile_photo_id TEXT,
    joined_at        TEXT DEFAULT CURRENT_TIMESTAMP,
    show_creator     INTEGER DEFAULT 1,
    character        TEXT DEFAULT 'None'
);

CREATE TABLE IF NOT EXISTS group_counts (
    chat_id       BIGINT PRIMARY KEY,
    message_count INTEGER DEFAULT 0
);

CREATE TABLE IF NOT EXISTS group_chats (
    chat_id   BIGINT PRIMARY KEY,
    title     TEXT,
    chat_type TEXT,
    active    INTEGER DEFAULT 1,
    added_at  TEXT DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS review_messages (
    media_id   BIGINT NOT NULL,
    chat_id    BIGINT NOT NULL,
    message_id BIGINT NOT NULL,
    caption    TEXT DEFAULT '',
    PRIMARY KEY (media_id, chat_id, message_id)
);

CREATE TABLE IF NOT EXISTS bot_settings (
    setting_key   TEXT PRIMARY KEY,
    setting_value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS moderation_audit (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    media_id       BIGINT NOT NULL,
    action         TEXT NOT NULL,
    moderator_id   BIGINT NOT NULL,
    moderator_name TEXT,
    created_at     TEXT DEFAULT CURRENT_TIMESTAMP
);

-- Persistent, per-user conversation state (replaces context.user_data).
CREATE TABLE IF NOT EXISTS conversation_state (
    user_id     BIGINT NOT NULL,
    state_key   TEXT NOT NULL,
    state_value TEXT,
    updated_at  TEXT DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, state_key)
);

-- Persistent counters backing the anti-spam limiter.
CREATE TABLE IF NOT EXISTS rate_limits (
    bucket       TEXT NOT NULL,
    user_id      BIGINT NOT NULL,
    count        INTEGER NOT NULL DEFAULT 0,
    window_start BIGINT NOT NULL,
    PRIMARY KEY (bucket, user_id)
);

CREATE INDEX IF NOT EXISTS idx_media_kind_approved ON media (kind, approved);
CREATE INDEX IF NOT EXISTS idx_media_sender       ON media (sender_id);
CREATE INDEX IF NOT EXISTS idx_votes_media         ON votes (media_id);
CREATE INDEX IF NOT EXISTS idx_users_username      ON users (username);
CREATE INDEX IF NOT EXISTS idx_conv_state_user     ON conversation_state (user_id);
"""

# --------------------------------------------------------------------------
# Foreign keys.
#
# These are applied idempotently. The import utility adds them *after* copying
# the historical SQLite data; if a legacy database contains a dangling reference
# the individual constraint is skipped (and reported) rather than failing the
# whole migration, so no historical data is ever destroyed.
#
# ``media.sender_id`` intentionally has no foreign key: legacy databases contain
# a handful of media rows whose sender never ran /start and therefore has no
# row in ``users``. Adding the constraint would make a faithful import fail.
# --------------------------------------------------------------------------
FOREIGN_KEY_SQL = """
DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_votes_media') THEN
        ALTER TABLE votes ADD CONSTRAINT fk_votes_media
            FOREIGN KEY (media_id) REFERENCES media (id) ON DELETE CASCADE;
    END IF;
END $$;

DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_owner_votes_media') THEN
        ALTER TABLE owner_votes ADD CONSTRAINT fk_owner_votes_media
            FOREIGN KEY (media_id) REFERENCES media (id) ON DELETE CASCADE;
    END IF;
END $$;

DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_moderation_audit_media') THEN
        ALTER TABLE moderation_audit ADD CONSTRAINT fk_moderation_audit_media
            FOREIGN KEY (media_id) REFERENCES media (id) ON DELETE CASCADE;
    END IF;
END $$;

DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_review_messages_media') THEN
        ALTER TABLE review_messages ADD CONSTRAINT fk_review_messages_media
            FOREIGN KEY (media_id) REFERENCES media (id) ON DELETE CASCADE;
    END IF;
END $$;

DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_group_counts_chat') THEN
        ALTER TABLE group_counts ADD CONSTRAINT fk_group_counts_chat
            FOREIGN KEY (chat_id) REFERENCES group_chats (chat_id) ON DELETE CASCADE;
    END IF;
END $$;

DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_roles_user') THEN
        ALTER TABLE roles ADD CONSTRAINT fk_roles_user
            FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE;
    END IF;
END $$;

DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_profile_photos_user') THEN
        ALTER TABLE profile_photos ADD CONSTRAINT fk_profile_photos_user
            FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE;
    END IF;
END $$;

DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_profile_votes_user') THEN
        ALTER TABLE profile_votes ADD CONSTRAINT fk_profile_votes_user
            FOREIGN KEY (profile_id) REFERENCES users (user_id) ON DELETE CASCADE;
    END IF;
END $$;
"""

# Backfill review_status for data imported from SQLite databases that predate
# the moderation columns. Mirrors the logic the old bot ran at startup.
BACKFILL_SQL = """
UPDATE media
   SET review_status = 'approved'
 WHERE approved = 1
   AND review_status = 'legacy_pending';
"""

ALL_SQL = SCHEMA_SQL + FOREIGN_KEY_SQL + BACKFILL_SQL
